"""Synthetic credit dataset generator with honest provenance (FR-1, constitution V).

This data is SYNTHETIC — generated from a fixed seed, containing NO real people
and NO real PII. A default label is produced from a transparent latent risk
function of the features (plus label noise), so a model can learn genuine signal
while everything remains reproducible and clearly labeled as synthetic.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .features.schema import CATEGORICAL_FIELDS, PROTECTED_VALUES, TARGET

PROVENANCE = (
    "SYNTHETIC DATA — generated by src/creditsentinel/dataset.py with a pinned seed. "
    "No real applicants, no real PII. The `default` label is drawn from a transparent "
    "latent risk function of the features plus label noise. A mild, deliberately small "
    "association between the protected `group` attribute and default is injected ONLY to "
    "make the fairness check non-trivial; `group` is never a model feature."
)


def generate(n: int = 8000, seed: int = 42) -> pd.DataFrame:
    """Return a reproducible synthetic applicant dataset."""
    rng = np.random.default_rng(seed)

    age = rng.integers(21, 70, size=n).astype(float)
    annual_income = np.clip(rng.normal(60000, 25000, size=n), 12000, 250000)
    employment_length = np.clip(rng.normal(6, 4, size=n), 0, 40)
    debt_to_income = np.clip(rng.normal(0.30, 0.15, size=n), 0.0, 1.2)
    credit_utilization = np.clip(rng.normal(0.45, 0.25, size=n), 0.0, 1.5)
    num_delinquencies = rng.poisson(0.5, size=n).astype(float)
    num_open_accounts = np.clip(rng.normal(9, 4, size=n), 0, 40).round()
    loan_amount = np.clip(rng.normal(15000, 9000, size=n), 1000, 60000)
    interest_rate = np.clip(rng.normal(13, 5, size=n), 3, 30)

    home_ownership = rng.choice(CATEGORICAL_FIELDS["home_ownership"], size=n, p=[0.45, 0.20, 0.35])
    purpose = rng.choice(CATEGORICAL_FIELDS["purpose"], size=n, p=[0.35, 0.25, 0.15, 0.10, 0.15])
    group = rng.choice(PROTECTED_VALUES, size=n, p=[0.6, 0.4])

    # Transparent latent risk (log-odds). Higher DTI/utilization/delinquencies/rate
    # increase risk; higher income/employment reduce it.
    z = (
        -3.0
        + 2.6 * debt_to_income
        + 1.8 * credit_utilization
        + 0.55 * num_delinquencies
        + 0.06 * (interest_rate - 13)
        - 1.2e-5 * (annual_income - 60000)
        - 0.04 * employment_length
        - 0.015 * (age - 45)
        + 0.15 * (group == "B")  # small injected disparity for fairness demo only
    )
    p_default = 1.0 / (1.0 + np.exp(-z))
    default = rng.binomial(1, p_default).astype(int)

    df = pd.DataFrame(
        {
            "age": age,
            "annual_income": annual_income,
            "employment_length": employment_length,
            "debt_to_income": debt_to_income,
            "credit_utilization": credit_utilization,
            "num_delinquencies": num_delinquencies,
            "num_open_accounts": num_open_accounts,
            "loan_amount": loan_amount,
            "interest_rate": interest_rate,
            "home_ownership": home_ownership,
            "purpose": purpose,
            "group": group,
            TARGET: default,
        }
    )
    return df


def write_dataset(data_dir: str | Path, n: int = 8000, seed: int = 42) -> Path:
    """Generate and persist the dataset plus a PROVENANCE note. Returns the path."""
    data_dir = Path(data_dir)
    data_dir.mkdir(parents=True, exist_ok=True)
    df = generate(n=n, seed=seed)
    path = data_dir / "applicants.parquet"
    df.to_parquet(path, index=False)
    (data_dir / "PROVENANCE.md").write_text(
        f"# Data Provenance\n\n{PROVENANCE}\n\n- rows: {n}\n- seed: {seed}\n"
        f"- default rate: {df[TARGET].mean():.4f}\n",
        encoding="utf-8",
    )
    return path


def get_dataset(settings=None, n: int = 8000, seed: int = 42) -> tuple[pd.DataFrame, str]:
    """Return dataset (DataFrame, provenance_string) according to settings.data_source."""
    from .config import get_settings
    from .homecredit import HOMECREDIT_PROVENANCE, load_homecredit

    settings = settings or get_settings()
    if settings.data_source == "homecredit":
        df = load_homecredit(settings.homecredit_raw_path)
        return df, HOMECREDIT_PROVENANCE
    return generate(n=n, seed=seed), PROVENANCE

